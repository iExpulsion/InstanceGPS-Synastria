"""Write InstanceGPS_Synastria/Difficulties.lua: each boss creature's difficulty versions.

    python tools/difficulties.py [path to SynastriaData] [path to InstanceGPS's Data.lua]

Synastria's loot database lists a boss's heroic and 25-player drops under the creature's difficulty
version ("Lord Marrowgar (3)" for 25 heroic), and the 3.3.5 client has no way to look those up. This
reads them from SynastriaData's creatures.csv (difficulty_entry_1..3, extracted from the client's
WoWExt files) for every creature InstanceGPS (and Overrides.lua) counts as a boss, and writes the
creature IDs only. Run it again after a client patch or an InstanceGPS data update.

Defaults: SynastriaData and InstanceGPS checkouts next to this repo.
"""
import csv, glob, os, sys

from lupa import lua51

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADDON = glob.glob(os.path.join(ROOT, "InstanceGPS_*"))[0]
SYN = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "SynastriaData")
BASE = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "..", "InstanceGPS", "InstanceGPS", "Data.lua")
OUT = os.path.join(ADDON, "Difficulties.lua")

L = lua51.LuaRuntime(unpack_returned_tuples=True)
ns = L.eval("{}")
L.eval("function(src, ns) local f = assert(loadstring(src)) f('InstanceGPS', ns) end")(
    open(BASE, encoding="utf8").read(), ns)
L.execute("calls = {} InstanceGPS = {} function InstanceGPS:Override(name, t) calls[#calls + 1] = t end")
L.execute(open(os.path.join(ADDON, "Overrides.lua"), encoding="utf8").read())

npcs = set()
for inst in ns.Instances.values():
    for b in inst.bosses.values():
        npcs.update(int(n) for n in (b.npcs or {}).values())
for t in L.globals().calls.values():
    for inst in t.values():
        if inst and inst.bosses:
            for b in inst.bosses.values():
                if b and b.npcs:
                    npcs.update(int(n) for n in b.npcs.values())

entries = {}
with open(os.path.join(SYN, "data", "world", "creatures.csv"), encoding="utf8") as f:
    for r in csv.DictReader(f):
        cid = int(r["id"])
        slots = {s: int(r["difficulty_entry_%d" % s]) for s in (1, 2, 3) if r["difficulty_entry_%d" % s]}
        if cid in npcs and slots:
            entries[cid] = slots


def lua(slots):
    if sorted(slots) == list(range(1, len(slots) + 1)):
        return "{%s}" % ",".join(str(slots[s]) for s in sorted(slots))
    return "{%s}" % ",".join("[%d]=%d" % (s, slots[s]) for s in sorted(slots))


lines = [
    "-- Generated by tools/difficulties.py from Synastria's client data. Do not edit.",
    "-- Boss creature ID -> its difficulty versions: [1] heroic or 25 normal, [2] 10 heroic, [3] 25 heroic.",
    "local _, ns = ...",
    "ns.DifficultyEntries = {",
]
lines += [" [%d]=%s," % (cid, lua(entries[cid])) for cid in sorted(entries)]
lines.append("}")
with open(OUT, "w", encoding="utf8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("%s: %d of %d boss creatures have difficulty versions" % (os.path.relpath(OUT, ROOT), len(entries), len(npcs)))
